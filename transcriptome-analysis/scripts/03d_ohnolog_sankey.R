#!/usr/bin/env Rscript
# =============================================================================
# 03d_ohnolog_sankey.R
# -----------------------------------------------------------------------------
# Purpose
#   Alluvial (Sankey) diagrams of ohnolog pair SOM cluster assignments, one per
#   (map × rediploidization class × constitutive filter) combination. Ribbon
#   width = number of pairs connecting two clusters; ribbon colour = log2
#   observed/expected under random pairing (skyblue = depleted, seashell =
#   expected, lightcoral = enriched).
#
# Inputs
#   <data_path>/c1_coclustering_results.RData   (generated by 03)
#     Provides `devmap_result`, `bodymap_result` — each a list with a `$detail`
#     data frame containing one row per ohnolog pair with columns
#     `cluster1`, `cluster2` (raw SOM unit IDs) and `proxiPhylogeny` ∈
#     {AORe, LORe}.
#   <data_path>/c1_extended_results.RData        (generated by 03b, for completeness)
#   data/ohnolog/som_info.RData                     (for `sb_som_info`, which
#     carries `class_max` and `constitutive_class` per BodyMap cluster).
#
# Outputs → <outdir>/panels/
#   C1_{devmap,bodymap}_sankey_{early,late}[.noconst].{pdf,png}
#
# Key choices
#   * Expected ribbon size under the null of random pairing is derived from
#     gene marginals: for each gene copy, P(in cluster k) = n_k / N_genes.
#     Given `n_pairs` total pairs and classical 2-gene-per-pair counting:
#       E(A,B) = n_pairs * 2 * p_A * p_B   for A ≠ B
#       E(A,A) = n_pairs *     p_A * p_B   for A = B   (no factor-of-2)
#     `pmax(expected, 0.5)` floor avoids divide-by-zero / -Inf when a cluster
#     pair never co-occurs in the observed data.
#   * Colour legend uses a phantom zero-size point (geom_point) so ggplot
#     generates a continuous colourbar for the manually-coloured ribbons.
#   * P* (unit 9) excluded from DevMap throughout.
# =============================================================================

suppressPackageStartupMessages({
  library(tidyverse)
  library(ggalluvial)
  library(viridisLite)
  library(scales)
})

# --- Global font (Helvetica) ------------------------------------------------
