  detail_sub <- devmap_result$detail %>%
    filter(proxiPhylogeny == redip, cluster1 != 9, cluster2 != 9)
  lbl <- ifelse(redip == "AORe", "Early", "Late")

  make_upset_plot(detail_sub, devmap_label_map, devmap_label_order, devmap_palette,
    file.path(outdir, paste0("C1_devmap_upset_", tolower(lbl))))

  nc_detail <- detail_sub %>%
    filter(!cluster1 %in% devmap_constitutive, !cluster2 %in% devmap_constitutive)
  nc_labels <- devmap_label_order[!devmap_label_order %in% c("C1","C2","C3","C4")]
  nc_palette <- devmap_palette[nc_labels]

  make_upset_plot(nc_detail, devmap_label_map, nc_labels, nc_palette,
