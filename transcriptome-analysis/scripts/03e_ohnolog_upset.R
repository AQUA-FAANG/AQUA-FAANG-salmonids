load("data/ohnolog/som_info.RData")

# Collapse BodyMap cluster → dominant tissue (full names used here, unlike
# the abbreviated variant in 03d, because UpSet set labels have more room).
# `case_when` clause order encodes priority when `class_max` mentions multiple
# tissues; `Multi` catches anything unclassified.
bodymap_tissue_for_cluster <- function(cluster_num) {
  info <- sb_som_info[cluster_num, ]
  if (!is.null(info$constitutive_class) && info$constitutive_class == "TRUE")
    return("Constitutive")
  cm <- info$class_max
  case_when(
    grepl("Brain", cm)      ~ "Brain",
    grepl("Muscle", cm)     ~ "Muscle",
    grepl("Liver", cm)      ~ "Liver",
    grepl("Testes", cm)     ~ "Testes",
    grepl("Ova", cm)        ~ "Ovary",
    grepl("Gill", cm)       ~ "Gill",
    grepl("HeadKidney", cm) ~ "Head_kidney",
    grepl("Intestine", cm)  ~ "Intestine",
    TRUE                    ~ "Multi"
  )
}

bm_tissue_labels <- sapply(1:36, bodymap_tissue_for_cluster)
names(bm_tissue_labels) <- as.character(1:36)

bm_tissue_order <- c("Brain", "Muscle", "Gill", "Head_kidney",
                      "Intestine", "Liver", "Testes", "Ovary",
                      "Multi", "Constitutive")

tissue_cols <- c(
  "Brain" = "#dce648ff", "Muscle" = "salmon", "Liver" = "#8a0000ff",
  "Testes" = "forestgreen", "Ovary" = "#ffa300ff", "Gill" = "red2",
  "Head_kidney" = "black", "Intestine" = "hotpink",
  "Multi" = "skyblue", "Constitutive" = "#becacaff"
)

bm_constitutive <- which(sapply(1:36, function(i)
  !is.null(sb_som_info[i,]$constitutive_class) && sb_som_info[i,]$constitutive_class == "TRUE"))

for (redip in c("AORe", "LORe")) {
  detail_sub <- bodymap_result$detail %>% filter(proxiPhylogeny == redip)
  lbl <- ifelse(redip == "AORe", "Early", "Late")

  make_tissue_upset(detail_sub, bm_tissue_labels, bm_tissue_order, tissue_cols,
    file.path(outdir, paste0("C1_bodymap_upset_", tolower(lbl))))

  nc_detail <- detail_sub %>%
    filter(!cluster1 %in% bm_constitutive, !cluster2 %in% bm_constitutive)
  nc_tissue_order <- bm_tissue_order[bm_tissue_order != "Constitutive"]
  nc_tissue_cols <- tissue_cols[nc_tissue_order]

  make_tissue_upset(nc_detail, bm_tissue_labels, nc_tissue_order, nc_tissue_cols,
    file.path(outdir, paste0("C1_bodymap_upset_", tolower(lbl), "_noconst")))
}

