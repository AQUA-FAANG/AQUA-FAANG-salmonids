#!/usr/bin/env Rscript
# =============================================================================
# 03g_early_late_ratio_panel.R
# -----------------------------------------------------------------------------
# Purpose
#   Per-cluster Early-to-Late gene ratio panels for the C1 ohnolog SOM
#   analysis (R1-C6). Bar height = AORe/LORe ratio per cluster (with
#   Haldane–Anscombe +0.5 correction). Bars are filled with a visually
#   stacked AORe/LORe percentage breakdown drawn as two geom_rect layers,
#   each labelled in-bar with the cluster's AORe% / LORe%. 95% CI on the
#   log-ratio is overlaid as error bars. The dashed horizontal line marks
#   the genome-wide Early/Late ratio computed from the singleton-inclusive
#   composition pool. ▲ / ▼ + asterisks above each bar mark per-cluster
#   deviations from the genome-wide ratio (binomial test, BH-adjusted).
#
#   Companion panel: per-cluster co-clustering rate ratio (LORe rate /
#   AORe rate) with 95% CI on the log-RR. Min-n gated.
#
# Inputs
#   <data_path>/c1_extended_results.RData   (generated by 03b)
#     devmap_gene_counts, bodymap_gene_counts          (composition table
#                                                       with el_ratio + CI)
#     devmap_ratio_tests, bodymap_ratio_tests          (per-cluster binomial
#                                                       vs genome-wide ratio)
#     devmap_coclust_ratio_tests, bodymap_coclust_ratio_tests
#                                                      (per-cluster log-RR
#                                                       on co-clustering)
# =============================================================================

