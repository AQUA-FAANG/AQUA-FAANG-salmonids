# =============================================================================
# Per-cluster co-clustering RATE ratio (A1 alternate panel)
# Late/Early co-clustering rate per cluster, with 95% CI on the log-RR.
# Clusters failing the min-n gate are greyed out and shown without CI bars.
# =============================================================================

build_coclust_ratio_df <- function(tbl, label_lookup) {
  tbl %>%
    mutate(
      marker = ifelse(!is.na(sig_fisher) & sig_fisher != "" & pass_n,
                      sig_fisher, ""),
      rr_plot    = ifelse(pass_n, rr,    NA_real_),
      rr_lo_plot = ifelse(pass_n, rr_lo, NA_real_),
      rr_hi_plot = ifelse(pass_n, rr_hi, NA_real_)
    )
}

# DevMap co-clustering ratio panel
devmap_cc <- build_coclust_ratio_df(devmap_coclust_ratio_tests$tests) %>%
  filter(cluster != 9) %>%
  mutate(
    label_ms = devmap_label_map[as.character(cluster)],
    label_ms = factor(label_ms,
      levels = devmap_label_map[as.character(full_devmap_order)])
  )

devmap_cc_plot <- function(df) {
  ymax <- max(c(df$rr_hi_plot, df$rr), na.rm = TRUE)
  ggplot(df, aes(x = label_ms, y = rr)) +
    geom_col(aes(fill = pass_n), colour = "grey20", linewidth = 0.3, width = 0.7) +
    geom_errorbar(aes(ymin = rr_lo_plot, ymax = rr_hi_plot),
                  width = 0.2, colour = "grey15", linewidth = 0.4,
                  na.rm = TRUE) +
    geom_hline(yintercept = 1, linetype = "dashed",
               colour = "grey30", linewidth = 0.6) +
    geom_text(aes(y = pmax(rr_hi_plot, rr, na.rm = TRUE) + ymax * 0.04,
                  label = marker),
              vjust = 0, size = 3.6, fontface = "bold",
              family = font_family, colour = "grey15", na.rm = TRUE) +
    scale_fill_manual(values = c("TRUE" = "grey35", "FALSE" = "grey80"),
                      guide = "none") +
    scale_y_continuous(expand = expansion(mult = c(0, 0.18))) +
    labs(x = "DevMap SOM cluster",
         y = "Co-clustering ratio (Early / Late)") +
    theme(
      panel.grid.major.x = element_blank(),
      axis.text.x        = element_text(face = "bold")
    )
}

p_dev_cc <- devmap_cc_plot(devmap_cc)
