simplify_tissue <- function(lbl) {
  case_when(
    grepl("Brain", lbl)        ~ "Brain",
    grepl("Muscle", lbl)       ~ "Muscle",
    grepl("Liver", lbl)        ~ "Liver",
    grepl("Testes", lbl)       ~ "Testes",
    grepl("Ova", lbl)          ~ "Ovary",
    grepl("Gill", lbl)         ~ "Gill",
    grepl("HeadKidney", lbl)   ~ "Head kidney",
    grepl("Intestine", lbl)    ~ "Intestine",
    grepl("Constitutive", lbl) ~ "Constitutive",
    TRUE                        ~ "Multi"
  )
}

