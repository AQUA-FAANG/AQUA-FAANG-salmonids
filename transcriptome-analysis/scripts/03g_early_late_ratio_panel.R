  mutate(tissue = simplify_tissue(label),
         tissue = factor(tissue, levels = tissue_order))

bodymap_cc_plot <- function(df) {
  df <- df %>% arrange(tissue, cluster)
  df$cluster_f <- factor(df$cluster, levels = unique(df$cluster))
  ymax <- max(c(df$rr_hi_plot, df$rr), na.rm = TRUE)
  ggplot(df, aes(x = cluster_f, y = rr)) +
    geom_col(aes(fill = pass_n), colour = "grey20", linewidth = 0.3, width = 0.7) +
    geom_errorbar(aes(ymin = rr_lo_plot, ymax = rr_hi_plot),
                  width = 0.2, colour = "grey15", linewidth = 0.4,
                  na.rm = TRUE) +
    geom_hline(yintercept = 1, linetype = "dashed",
               colour = "grey30", linewidth = 0.6) +
    geom_text(aes(y = pmax(rr_hi_plot, rr, na.rm = TRUE) + ymax * 0.04,
                  label = marker),
              vjust = 0, size = 3.4, fontface = "bold",
              family = font_family, colour = "grey15", na.rm = TRUE) +
    scale_fill_manual(values = c("TRUE" = "grey35", "FALSE" = "grey80"),
                      guide = "none") +
    scale_y_continuous(expand = expansion(mult = c(0, 0.18))) +
    facet_grid(. ~ tissue, scales = "free_x", space = "free_x") +
    labs(x = "BodyMap SOM cluster",
         y = "Co-clustering ratio (Early / Late)") +
    theme(
      panel.grid.major.x = element_blank(),
      strip.background   = element_rect(fill = "grey92", colour = NA),
      strip.text         = element_text(face = "bold", size = 9),
      axis.text.x        = element_text(size = 9)
    )
}

p_body_cc <- bodymap_cc_plot(bodymap_cc)
save_gg(file.path(outdir, "C1_bodymap_coclustering_ratio_per_cluster"),
        p_body_cc, 12, 4)

cat("\nDone.\n")
