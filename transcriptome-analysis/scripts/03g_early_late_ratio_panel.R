# Final figure-pack target: inner panel rectangle = 252.98 pt x 114.75 pt
# (3.514 x 1.594 in). Diego scales/aligns in Illustrator after export, so we
# ship at a slightly larger canvas with axes + labels and set every text element
# to 6 pt Helvetica regular black (minimum legible size at the final scale).
# x-axis cluster numbers rotated 45 deg so two-digit display ids don't crowd
# the narrow facets. No tissue strip text — tissue is communicated by bar fill
# (Diego adds tissue annotations in Illustrator).
font_family <- "Helvetica"
text_pt <- 6   # final-size minimum (pt). geom_text() takes mm: 6 pt = 2.117 mm.
text_mm <- text_pt / .pt   # ggplot2's .pt = 72.27/25.4

bodymap_ratio_plot <- function(df) {
  # Sort within each tissue facet by display_id so labels run ascending
  # (e.g. Brain facet -> 1,2,3,4,5,21,22). Tissue-specific bars (display_id
  # <= 20) precede Multi bars (>=21) within each facet by construction.
  df <- df %>% arrange(tissue, display_id)
  df$display_f <- factor(df$display_id, levels = unique(df$display_id))
  ymax <- max(df$el_ratio, na.rm = TRUE) * 1.15
  ggplot(df, aes(x = display_f, y = el_ratio, fill = fill_cat)) +
    geom_col(colour = "black", linewidth = 0.25, width = 0.8) +
    geom_hline(yintercept = bodymap_genome_ratio, linetype = "dashed",
               colour = "black", linewidth = 0.4) +
    geom_text(aes(label = marker, y = el_ratio + ymax * 0.02),
              vjust = 0, size = text_mm, family = font_family,
              colour = "black") +
    scale_fill_manual(values = tissue_cols, name = "Tissue") +
    scale_y_continuous(expand = expansion(mult = c(0, 0.18))) +
    facet_grid(. ~ tissue, scales = "free_x", space = "free_x") +
    labs(x = NULL,
         y = "Early-to-Late gene ratio") +
    theme_bw(base_size = text_pt, base_family = font_family) +
    theme(
      text               = element_text(colour = "black", family = font_family),
      axis.text          = element_text(colour = "black", size = text_pt),
      axis.text.x        = element_text(angle = 45, hjust = 1, vjust = 1,
                                        size = text_pt, colour = "black"),
      axis.title         = element_text(colour = "black", size = text_pt),
      axis.ticks         = element_line(colour = "black", linewidth = 0.3),
      # Each tissue facet kept boxed in via panel.border; strip label sits on
      # top, tilted 45 deg, with no grey background box behind the text.
      panel.border       = element_rect(colour = "black", fill = NA,
                                        linewidth = 0.3),
      strip.background   = element_blank(),
      strip.text.x       = element_text(angle = 45, hjust = 0, vjust = 0,
                                        size = text_pt, colour = "black",
                                        margin = margin(0, 0, 1, 0, "pt")),
      strip.placement    = "outside",
      strip.clip         = "off",
      panel.grid         = element_blank(),
      panel.spacing.x    = unit(2, "pt"),
      legend.position    = "none",
      plot.margin        = margin(20, 14, 2, 2, "pt")
    )
}

p_body_const   <- bodymap_ratio_plot(bodymap_df)
p_body_noconst <- bodymap_ratio_plot(bodymap_df %>% filter(tissue != "Constitutive"))

# Canvas sized so the inner panel area lands close to 252.98 x 114.75 pt
