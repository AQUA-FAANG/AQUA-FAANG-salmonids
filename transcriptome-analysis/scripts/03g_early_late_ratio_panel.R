save_gg <- function(fname_base, p, w, h, dpi = 300) {
  name    <- basename(fname_base)
  map     <- if (grepl("_bodymap_", name)) "bodymap" else "devmap"
  variant <- if (grepl("_noconst$", name)) "noconst" else "const"
  pdf_dir <- file.path(outdir, "pdf", map, variant)
  png_dir <- file.path(outdir, "png", map, variant)
  dir.create(pdf_dir, showWarnings = FALSE, recursive = TRUE)
  dir.create(png_dir, showWarnings = FALSE, recursive = TRUE)
  ggsave(file.path(pdf_dir, paste0(name, ".pdf")), p, width = w, height = h,
         device = cairo_pdf)
  ggsave(file.path(png_dir, paste0(name, ".png")), p, width = w, height = h, dpi = dpi)
  cat("  Saved", name, "->", map, "/", variant, "\n")
  if (name %in% names(manuscript_pack_map)) {
    pack_name <- manuscript_pack_map[[name]]
    ggsave(file.path(manuscript_pack_dir, paste0(pack_name, ".pdf")),
           p, width = w, height = h, device = cairo_pdf)
    ggsave(file.path(manuscript_pack_dir, paste0(pack_name, ".png")),
           p, width = w, height = h, dpi = dpi)
    cat("  Mirrored -> manuscript_R1_panels/", pack_name, "\n", sep = "")
  }
}

# Build a long-format frame with one row per (cluster, segment) where each
# segment is the height contribution of AORe vs LORe to the bar (bar total
# height = el_ratio). geom_col(position="stack") then handles facet x-axes
# correctly. Within a bar AORe sits at the bottom, LORe sits on top, in
# proportion to the cluster's composition.
#
# Segment heights:  seg_AORe = el_ratio * pct_AORe/100,  seg_LORe = ratio - seg_AORe
# Label y-positions:  AORe -> seg_AORe / 2     (centre of AORe segment)
#                     LORe -> seg_AORe + (el_ratio - seg_AORe) / 2
to_stacked_long <- function(df) {
  base_cols <- intersect(c("cluster", "label", "AORe", "LORe", "total",
                           "pct_AORe", "pct_LORe", "el_ratio",
                           "ratio_lo", "ratio_hi", "label_ms", "tissue",
                           "marker"), colnames(df))
  df %>%
    select(all_of(base_cols)) %>%
    mutate(seg_AORe = el_ratio * pct_AORe / 100,
           seg_LORe = el_ratio - seg_AORe,
           label_y_AORe = seg_AORe / 2,
           label_y_LORe = seg_AORe + seg_LORe / 2) %>%
    pivot_longer(cols = c(seg_AORe, seg_LORe),
                 names_to  = "segment_name",
                 values_to = "seg_height") %>%
    # Levels ordered so AORe stacks at the bottom, LORe at the top with
    # position_stack(reverse = TRUE) in the geom layer.
    mutate(segment = factor(sub("seg_", "", segment_name),
                            levels = c("AORe", "LORe")),
           pct_lab = ifelse(segment == "AORe",
                            sprintf("%.0f%%", pct_AORe),
                            sprintf("%.0f%%", pct_LORe)),
           seg_label_y = ifelse(segment == "AORe",
                                label_y_AORe, label_y_LORe))
}

# =============================================================================
# DEVMAP: composition ratio panel (A(ii))
# =============================================================================

devmap_genome_ratio <- with(devmap_gene_counts,
                            (sum(AORe) + 0.5) / (sum(LORe) + 0.5))

devmap_df <- devmap_gene_counts %>%
  filter(cluster != 9) %>%                          # drop P*
  left_join(devmap_ratio_tests$tests %>%
              select(cluster, padj, sig, enrichment),
            by = "cluster") %>%
  mutate(
    label_ms = devmap_label_map[as.character(cluster)],
    label_ms = factor(label_ms,
      levels = devmap_label_map[as.character(full_devmap_order)]),
    # `enrichment` from build_ratio_tests is keyed on LORe fraction. In the
    # Early-to-Late ratio panel we want ▲ = Early-enriched (bar taller than
    # genome-wide), which is the *opposite* of LORe-enriched, so flip the
    # mapping here.
    marker = case_when(
      is.na(sig) | sig == ""        ~ "",
      enrichment == "up"            ~ paste0("▼", sig),  # LORe-enriched -> Early-depleted
      enrichment == "down"          ~ paste0("▲", sig),  # LORe-depleted -> Early-enriched
      TRUE                           ~ ""
    )
  )

devmap_ratio_plot <- function(df) {
  ymax <- max(df$el_ratio, na.rm = TRUE) * 1.15
  ggplot(df, aes(x = label_ms, y = el_ratio,
                 fill = as.character(cluster))) +
    geom_col(colour = "grey20", linewidth = 0.3, width = 0.75) +
    geom_hline(yintercept = devmap_genome_ratio, linetype = "dashed",
               colour = "grey30", linewidth = 0.6) +
    annotate("text", x = Inf, y = devmap_genome_ratio,
             label = sprintf("genome-wide %.2f", devmap_genome_ratio),
             hjust = 1.05, vjust = -0.4, size = 3.2,
             family = font_family, colour = "grey30") +
    geom_text(aes(label = marker, y = el_ratio + ymax * 0.02),
              vjust = 0, size = 3.6, fontface = "bold",
              family = font_family, colour = "grey15") +
    scale_fill_manual(values = devmap_palette, guide = "none") +
    scale_y_continuous(expand = expansion(mult = c(0, 0.18))) +
    labs(x = "DevMap SOM cluster",
         y = "Early-to-Late gene ratio (AORe / LORe)") +
    theme(
      panel.grid.major.x = element_blank(),
      axis.text.x        = element_text(face = "bold")
    )
}

