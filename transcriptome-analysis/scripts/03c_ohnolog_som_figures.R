# Collapse a BodyMap cluster's compound `class_max` label (e.g. "Brain_Gill",
# "Ova_Matured") into a single dominant tissue category.
# Note: `case_when` is evaluated top-down — the order of clauses encodes
# priority when a label contains multiple tissue tokens. "Multi" is the
# catch-all for genuinely mixed/non-specific clusters.
# Args:  lbl — character vector of BodyMap class_max strings.
# Returns: character vector in `tissue_order`.
simplify_tissue <- function(lbl) {
  case_when(
    grepl("Brain", lbl)        ~ "Brain",
    grepl("Muscle", lbl)       ~ "Muscle",
    grepl("Liver", lbl)        ~ "Liver",
    grepl("Testes", lbl)       ~ "Testes",
    grepl("Ova", lbl)          ~ "Ovary",
    grepl("Gill", lbl)         ~ "Gill",
    grepl("HeadKidney", lbl)   ~ "Head kidney",
    grepl("Intestine", lbl)    ~ "Intestine",
    grepl("Constitutive", lbl) ~ "Constitutive",
    TRUE                        ~ "Multi"
  )
}

