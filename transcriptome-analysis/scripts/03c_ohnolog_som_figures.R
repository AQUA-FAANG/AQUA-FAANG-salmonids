# Save a ggplot to paired PDF + PNG outputs, routed automatically into
# panels/{pdf|png}/{devmap|bodymap}/{const|noconst}/. The routing keys are
# read from the filename:
#   * "_devmap_" / "_bodymap_" in the name → map subfolder
#   * "_noconst" suffix                    → noconst/ ; otherwise const/
# Call sites can keep passing `file.path(outdir, "C1_...")` as before;
# we strip the directory part with basename() and re-route from there.
# Args:
#   fname_base — path or bare name without extension.
#   p          — ggplot object.
#   w, h       — width/height in inches.
#   dpi        — raster resolution for the PNG only (PDF is vector).
# Returns: invisible NULL (called for its side effect).
save_gg <- function(fname_base, p, w, h, dpi = 300) {
  name    <- basename(fname_base)
  map     <- if (grepl("_bodymap_", name)) "bodymap" else "devmap"
  variant <- if (grepl("_noconst$", name)) "noconst" else "const"
  pdf_dir <- file.path(outdir, "pdf", map, variant)
  png_dir <- file.path(outdir, "png", map, variant)
  dir.create(pdf_dir, showWarnings = FALSE, recursive = TRUE)
  dir.create(png_dir, showWarnings = FALSE, recursive = TRUE)
  # cairo_pdf handles Unicode glyphs (▲ / ▼ / ↑ / ↓) properly; the default
  # pdf() device uses a Type 1 encoding that chokes on them.
  ggsave(file.path(pdf_dir, paste0(name, ".pdf")), p, width = w, height = h,
         device = cairo_pdf)
  ggsave(file.path(png_dir, paste0(name, ".png")), p, width = w, height = h, dpi = dpi)
  cat("  Saved", name, "→", map, "/", variant, "\n")
}

