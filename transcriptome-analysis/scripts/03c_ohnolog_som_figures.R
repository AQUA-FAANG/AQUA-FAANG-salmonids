#
# Each SOM cluster's full Ssal gene roster is partitioned into:
#   Early      nSsal==2 & proxiPhylogeny==AORe   (red   #c0392b)
#   Late       nSsal==2 & proxiPhylogeny==LORe   (blue  #2980b9)
#   Singleton  nSsal==1                           (dark grey #7f8c8d)
#   Other      rest (nSsal>=3, cryptic, NA …)     (light grey #bdc3c7)
#
# Two panels per map: absolute counts and within-cluster proportion.
# Bottom-to-top stack order: Late, Early, Singleton, Other — keeps the two
# ohnolog categories adjacent and at the baseline for cross-cluster
# comparison.
#
# Cluster ID labels on the x-axis sit inside a coloured square using the
# SOM palette when the `ggtext` package is available; otherwise the script
# falls back to plain axis text (Diego can add the squares in Illustrator).
# =============================================================================
composition_cols <- c("Early"     = "#c0392b",
                      "Late"      = "#2980b9",
                      "Singleton" = "#7f8c8d",
                      "Other"     = "#bdc3c7")

# Stack order driven by data: biggest mean within-cluster proportion at the
# bottom, smallest at the top. Computed over non-constitutive clusters of
# BOTH maps so the category order is stable across DevMap and BodyMap
# panels (avoids confusing the reader with swapped stacks).
compute_composition_order <- function(composition_df, labels_df) {
  composition_df %>%
    left_join(labels_df, by = "cluster") %>%
    filter(label != "Constitutive") %>%
    group_by(category) %>% summarise(mean_pct = mean(pct), .groups = "drop") %>%
    arrange(desc(mean_pct)) %>% pull(category)
}
dev_order_src <- compute_composition_order(devmap_composition,  devmap_labels)
bm_order_src  <- compute_composition_order(bodymap_composition, bodymap_labels)

# Weighted merge: average of the two rankings so both maps stack identically.
# Factor level order: biggest-mean-pct first, smallest last. Combined with
# `position_stack(reverse = TRUE)` / `position_fill(reverse = TRUE)` in the
# plotting helpers, this places the biggest slice at the BOTTOM of the stack.
composition_levels <- names(sort(
  c(sapply(c("Early","Late","Singleton","Other"), function(cat) {
      (match(cat, dev_order_src) + match(cat, bm_order_src)) / 2
    })),
  decreasing = FALSE))   # ascending rank = biggest pct first
cat("Composition stack order (bottom→top):",
    paste(composition_levels, collapse = " → "), "\n")

