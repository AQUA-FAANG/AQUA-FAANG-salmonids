# Build "<span …>LABEL</span>" HTML that renders as a white-on-colour pill
# under ggtext::element_markdown(). palette_vec is named by the display label.
make_square_labels <- function(labels_in_order, palette_vec) {
  if (!use_ggtext) return(setNames(labels_in_order, labels_in_order))
  cols <- palette_vec[labels_in_order]
  # Pick black or white text depending on the palette colour brightness so
  # grey and yellow pills both read clearly.
  rgb_mat <- col2rgb(cols)
  lum     <- 0.299 * rgb_mat[1, ] + 0.587 * rgb_mat[2, ] + 0.114 * rgb_mat[3, ]
  fg      <- ifelse(lum > 150, "black", "white")
  html <- sprintf(
    "<span style='background-color:%s; color:%s; padding:1px 4px; border-radius:2px;'><b>%s</b></span>",
    cols, fg, labels_in_order)
  setNames(html, labels_in_order)
}

