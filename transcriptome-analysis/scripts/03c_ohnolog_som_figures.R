# --- Aggregate helpers -----------------------------------------------------
# For the by-stage / by-tissue aggregates we need the same pair of tests
# (vs class mean, vs genome-wide LORe fraction) at the aggregate level —
# so we recompute them on the rolled-up totals.
#
# Args:
#   agg_df — tibble with (group_col, proxiPhylogeny, total_genes,
#            total_partner_here, pct).
#   group_col — bare column name (stage_group or tissue).
#
# Returns: (means, sig_bars, sig_ratio).
build_aggregate_sig <- function(agg_df, group_col) {
  gc <- rlang::as_name(rlang::enquo(group_col))
  means <- agg_df %>%
    group_by(proxiPhylogeny) %>%
    summarise(mean_rate = sum(total_partner_here) / sum(total_genes),
              .groups = "drop")
  sig_bars <- agg_df %>%
    left_join(means, by = "proxiPhylogeny") %>%
    rowwise() %>%
    mutate(pval = if (total_genes > 0) {
        suppressWarnings(prop.test(total_partner_here, total_genes,
                                    p = mean_rate)$p.value)
      } else NA_real_) %>%
    ungroup() %>%
    group_by(proxiPhylogeny) %>%
    mutate(padj = p.adjust(pval, method = "BH"),
           sig  = case_when(padj < 0.001 ~ "***",
                            padj < 0.01  ~ "**",
                            padj < 0.05  ~ "*",
                            TRUE         ~ "")) %>%
    ungroup()
  # Ratio test per aggregate group: LORe vs AORe proportion
  ratio_df <- agg_df %>%
    select(all_of(gc), proxiPhylogeny, total_genes) %>%
    pivot_wider(names_from = proxiPhylogeny, values_from = total_genes,
                values_fill = 0) %>%
    mutate(total = AORe + LORe)
  p_lore_global <- sum(ratio_df$LORe) / sum(ratio_df$total)
  sig_ratio <- ratio_df %>%
    rowwise() %>%
    mutate(pval = if (total > 0) {
        suppressWarnings(binom.test(LORe, total, p = p_lore_global)$p.value)
      } else NA_real_) %>%
    ungroup() %>%
    mutate(padj = p.adjust(pval, method = "BH"),
           sig  = case_when(padj < 0.001 ~ "***",
                            padj < 0.01  ~ "**",
                            padj < 0.05  ~ "*",
                            TRUE         ~ ""),
           enrichment = ifelse((LORe / pmax(total, 1)) > p_lore_global,
                                "up", "down"))
  list(means = means, sig_bars = sig_bars, sig_ratio = sig_ratio,
       p_lore = p_lore_global)
}

