# Append ▲/▼ to a label when the ratio test is significant.
decorate_ratio_labels <- function(plain_labels, ratio_tbl,
                                  cluster_to_label_map = NULL) {
  # plain_labels: vector of display strings in axis order.
  # ratio_tbl:    a tests tibble with `cluster`, `sig`, `enrichment`.
  # cluster_to_label_map: named vector cluster_id → label for joining.
  if (!is.null(cluster_to_label_map)) {
    ratio_tbl <- ratio_tbl %>%
      mutate(lookup_label = cluster_to_label_map[as.character(cluster)])
    idx <- match(plain_labels, ratio_tbl$lookup_label)
  } else {
    idx <- match(plain_labels, ratio_tbl$cluster)
  }
  sig       <- ratio_tbl$sig[idx]
  enrich    <- ratio_tbl$enrichment[idx]
  suffix    <- ifelse(is.na(sig) | sig == "", "",
                      ifelse(enrich == "up", arrow_up, arrow_dn))
  paste0(plain_labels, ifelse(suffix == "", "", paste0(" ", suffix)))
}

