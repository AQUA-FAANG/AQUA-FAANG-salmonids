#!/usr/bin/env Rscript
# =============================================================================
# 03c_ohnolog_som_figures.R
# -----------------------------------------------------------------------------
# Purpose
#   Bar-chart panels for the C1 ohnolog SOM co-clustering analysis (R1-C6).
#   Emits six paired PDF/PNG figures per map (DevMap + BodyMap):
#     * per-cluster co-clustering rate (AORe vs LORe)        (all + _noconst)
#     * aggregated co-clustering rate by stage or tissue group
#     * per-cluster proportion of LORe genes                 (all + _noconst)
#
# Inputs
#   <data_path>/c1_extended_results.RData   (generated by 03b)
#     Provides `devmap_per_clust`, `bodymap_per_clust` (per-cluster
#     co-clustering tables with n_genes, n_partner_here, pct_coclustered,
#     proxiPhylogeny = {AORe, LORe}) and `devmap_gene_counts`,
#     `bodymap_gene_counts` (per-cluster gene counts with pct_LORe).
#
# Analysis chain
#   03  (run first)  → c1_coclustering_results.RData   (pair-level tables)
#   03b (run second) → c1_extended_results.RData       (gene/cluster tables — used here)
#   03c, 03d, 03e    (this + siblings) read the RData files and emit panels
#   04               stitches panels into supplementary composites
#
# Outputs → <outdir>/panels/
#   C1_{devmap,bodymap}_coclustering_per_cluster[.noconst].{pdf,png}
#   C1_devmap_coclustering_by_stage.{pdf,png}
#   C1_bodymap_coclustering_by_tissue.{pdf,png}
#   C1_{devmap,bodymap}_lore_proportion[.noconst].{pdf,png}
#
# Key choices
#   * P* (SOM unit 9) excluded throughout — it is treated separately in the
#     supplement and is not part of the manuscript's M/B/G/S/P scheme.
#   * The raw SOM unit IDs from kohonen (1..16) do NOT match the manuscript
#     labels (M1..P2, C1..C4); `desired_order` below remaps them.
#   * Constitutive clusters (C1-C4 in DevMap, constitutive_class=TRUE in
#     BodyMap) are dropped in the `_noconst` variants because they dilute
#     the stage/tissue-specific signal; both variants are emitted so the
#     composite figure (04) can draw from the preferred set.
#
# Downstream
#   * 04_composite_figures.R stitches `coclustering_by_{stage,tissue}` and
#     `lore_proportion_noconst` panels into Panel A of the supplementary
#     composite figures.
# =============================================================================

