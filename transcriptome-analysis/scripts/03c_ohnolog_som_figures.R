# --- plotting helpers ------------------------------------------------------
# One helper per map so we don't duplicate the position_fill / position_stack
# × faceting combinations four times.
# Per-cluster asterisk: one mark above each bar when ≥1 category cell
# deviates significantly from its genome-wide expectation. Colour = the
# category driving the deviation (biggest |log2(observed/expected)|
# among significant cells). Star count mirrors that driver's padj.
#
# We return one row per cluster with (x-axis value, colour driver,
# asterisk string). Empty for clusters with no significant deviation.
build_driver_marks <- function(sig_df, x_col) {
  sig_df %>%
    filter(sig != "") %>%
    mutate(abs_log2_fc = abs(log2(pmax(n, 0.5) / (total * p_cat)))) %>%
    group_by(cluster) %>%
    slice_max(abs_log2_fc, n = 1, with_ties = FALSE) %>%
    ungroup() %>%
    transmute(cluster, driver = as.character(category),
              sig, total) %>%
    # Return the user-supplied key (cluster_label or cluster) so the
    # caller can join by x-axis.
    rename(!!x_col := cluster)
}

# Build the per-cluster Early/Late composition bar panel for the DevMap map
# (`mode` = "prop" stacks to proportions; else raw counts) and save it via save_gg.
devmap_composition_plot <- function(df, mode, fname, labels_map, sig_df) {
  pos <- if (mode == "prop") position_fill(reverse = TRUE)
         else                 position_stack(reverse = TRUE)
  # Small expansion on top gives headroom for the asterisks.
  y_scale <- if (mode == "prop")
    scale_y_continuous(labels = scales::percent_format(accuracy = 1),
                       expand = expansion(mult = c(0, 0.08)))
  else
    scale_y_continuous(expand = expansion(mult = c(0, 0.08)))
  y_title <- if (mode == "prop") "Within-cluster gene composition"
             else "Gene count"

  # Per-cluster driver table joined on cluster → manuscript label via
  # devmap_label_map. Only clusters present in `df` are kept.
  cluster_to_label <- setNames(devmap_label_map,
                               names(devmap_label_map))
  marks <- sig_df %>%
    filter(sig != "", cluster %in% unique(df$cluster)) %>%
    mutate(abs_log2_fc = abs(log2(pmax(n, 0.5) / (total * p_cat)))) %>%
    group_by(cluster) %>%
    slice_max(abs_log2_fc, n = 1, with_ties = FALSE) %>%
    ungroup() %>%
    mutate(cluster_label = factor(
             cluster_to_label[as.character(cluster)],
             levels = levels(df$cluster_label)),
           driver = factor(as.character(category),
                           levels = c("Early","Late","Singleton","Other")),
           y_top  = if (mode == "prop") 1.0 else total)

  p <- ggplot(df, aes(x = cluster_label, y = n, fill = category)) +
    geom_col(position = pos, width = 0.7) +
    geom_text(data = marks,
              aes(x = cluster_label, y = y_top, label = sig, colour = driver),
              inherit.aes = FALSE, vjust = -0.3, size = 4.5,
              fontface = "bold", show.legend = FALSE) +
    scale_fill_manual(values = composition_cols, name = "Category",
                      breaks = c("Early", "Late", "Singleton", "Other")) +
    scale_colour_manual(values = composition_cols, guide = "none",
                        drop = FALSE) +
    scale_x_discrete(labels = labels_map) +
    y_scale +
    labs(x = "SOM cluster", y = y_title) +
    theme_bw(base_size = 11, base_family = font_family) +
    theme(axis.text.x = element_markdown(angle = 45, hjust = 1),
          panel.grid.major.x = element_blank(),
          legend.position    = "right")
  save_gg(fname, p, 10, 5)
}

# As devmap_composition_plot, but for the BodyMap map (tissue-grouped x axis).
bodymap_composition_plot <- function(df, mode, fname, labels_map, sig_df) {
  pos <- if (mode == "prop") position_fill(reverse = TRUE)
         else                 position_stack(reverse = TRUE)
  y_scale <- if (mode == "prop")
    scale_y_continuous(labels = scales::percent_format(accuracy = 1),
                       expand = expansion(mult = c(0, 0.08)))
  else
    scale_y_continuous(expand = expansion(mult = c(0, 0.08)))
  y_title <- if (mode == "prop") "Within-cluster gene composition"
             else "Gene count"

  # Match facet's (cluster, tissue) pair so the asterisk lands in the
  # correct tissue sub-panel — join on cluster then re-attach tissue.
  marks <- sig_df %>%
    mutate(cluster = as.character(cluster)) %>%
    filter(sig != "",
           cluster %in% as.character(unique(df$cluster))) %>%
    mutate(abs_log2_fc = abs(log2(pmax(n, 0.5) / (total * p_cat)))) %>%
    group_by(cluster) %>%
    slice_max(abs_log2_fc, n = 1, with_ties = FALSE) %>%
    ungroup() %>%
    left_join(df %>% distinct(cluster, tissue) %>%
                mutate(cluster = as.character(cluster)),
              by = "cluster") %>%
    mutate(cluster = factor(cluster, levels = levels(df$cluster)),
           driver  = factor(as.character(category),
                             levels = c("Early","Late","Singleton","Other")),
           y_top   = if (mode == "prop") 1.0 else total)

  p <- ggplot(df, aes(x = cluster, y = n, fill = category)) +
    geom_col(position = pos, width = 0.7) +
    geom_text(data = marks,
              aes(x = cluster, y = y_top, label = sig, colour = driver),
              inherit.aes = FALSE, vjust = -0.3, size = 3.2,
              fontface = "bold", show.legend = FALSE) +
    scale_fill_manual(values = composition_cols, name = "Category",
                      breaks = c("Early", "Late", "Singleton", "Other")) +
    scale_colour_manual(values = composition_cols, guide = "none",
                        drop = FALSE) +
    scale_x_discrete(labels = labels_map) +
    y_scale +
    facet_grid(~ tissue, scales = "free_x", space = "free_x") +
    labs(x = "SOM cluster", y = y_title) +
    theme_bw(base_size = 10, base_family = font_family) +
    theme(axis.text.x = element_markdown(angle = 45, hjust = 1, size = 7),
          strip.text = element_text(size = 7),
          panel.grid.major.x = element_blank(),
          legend.position    = "bottom")
  save_gg(fname, p, 14, 5)
}

